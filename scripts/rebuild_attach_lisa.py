#!/usr/bin/env python3
"""One-shot D-8 attachment; deleted at milestone F (REBUILD.md).

Read the pre-attachment `reg-build read` frames (including scb-lisa.sections.json).
Generate ordinary curation and Markdown subjects; never infer a delivery or identity.
The output directory must be new. --write-curation installs the reviewed output.

After retirement, run `read` with a scratch copy of curation/ whose inputs.toml
adds the original lisa input (scb-lisa, provider scb, register lisa-workbook,
catalog/source/SCB/lisa-variabellista-total-t-o-m-2024-2025.xlsx). That inspection
copy must also remove the generated block from readers/markdown.toml, so document
subjects retain their original n: keys. Neither edit changes published curation.
"""

import argparse
import collections
import json
import re
import tomllib
from pathlib import Path

from rebuild_convert import ROOT, Converter, literal
from rebuild_convert_cases import parse_selector, period_intervals
from rebuild_convert_groups import final_variables, normalize_sets
from rebuild_convert_identity import IdentityProjection
from rebuild_convert_selectors import OPEN, Snapshot, collapse

OWNER = ("scb", "r34")
MARKER = "# D-8 LISA attachment (generated by scripts/rebuild_attach_lisa.py)."
FAMILIES = {
    "Individ": {"individer-15plus", "individer-16plus"},
    "Företag": {"foretag"},
    "Arbetsställe": {"arbetsstallen"},
    "Födelseland": {"individer-fodelseland"},
    "Avlidna": {"individer-avlidna"},
    "In- och Utvandring": {"individer-in-utvandring"},
}


def records(path):
    with path.open() as stream:
        for line in stream:
            yield json.loads(line)


def base(path):
    return path.read_text().split(MARKER)[0].rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--frames", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--write-curation", action="store_true")
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=False)
    filtered = args.out / "frames"
    filtered.mkdir()
    registers = []
    with (filtered / "selected.jsonl").open("w") as output:
        for row in records(args.frames / "scb-export.jsonl"):
            if row["kind"] == "register":
                registers.append(row)
            if row.get("register") == "r34":
                output.write(json.dumps(row, ensure_ascii=False) + "\n")
    converter = Converter(filtered, args.out)
    path = ROOT / "curation/registers/scb/r34/curation.toml"
    original = base(path)
    generated_section = path.read_text().partition(MARKER)[2]
    authored_sets = []
    for block in re.split(
        r"(?=^\[\[statement\]\]$)", generated_section, flags=re.MULTILINE
    ):
        if not block.strip():
            continue
        statement = tomllib.loads(block)["statement"][0]
        if statement["kind"] == "set" and "sets" in statement.get("fields", {}):
            authored_sets.append(block)
    for number, statement in enumerate(tomllib.loads(original)["statement"]):
        converter.add(f"existing:{number}", *OWNER, statement)
    statements = converter.statements[OWNER]
    snapshot = Snapshot(converter, OWNER, statements)
    if snapshot.problem:
        raise ValueError(snapshot.problem)
    export_spellings = {r["column"].lower() for r in converter.rows[OWNER]}
    source_count = len(converter.rows[OWNER])
    reverse_tables = {
        v: k for (p, r, k), v in converter.tables.items() if (p, r) == OWNER
    }
    # Constructors are source rows before scalar/identity setters. Reuse D's source
    # snapshot and identity projection, including asserted occurrences in both.
    for number, (row, period) in enumerate(snapshot.rows):
        if number < source_count:
            continue
        table = next(t for (t, _), ids in snapshot.index.items() if number in ids)
        row.update(
            provider="scb",
            register="r34",
            table=reverse_tables[table],
            kind="occurrence",
            locator={"input": str(path.relative_to(ROOT)), "at": f"assert:{number}"},
            **{"from": period[0], "to": period[1]},
        )
        converter.rows[OWNER].append(row)
        converter.records.append(row)
    converter.identity = IdentityProjection(converter.records, converter.ledgers)
    effective, used, *_ = final_variables(converter, OWNER)
    corrected = [dict(row) for row, _ in snapshot.rows]
    periods = [period for _, period in snapshot.rows]
    curated = collections.defaultdict(set)
    for number, (row, _) in enumerate(snapshot.rows):
        if number >= source_count:
            # D-4 constructors already own their stated fields. Workbook setters
            # attach missing wording, not a second claim on authored sensitivity.
            curated["sensitive"].add(number)
    for record in statements.values():
        statement = record["statement"]
        address = parse_selector(statement["subject"])
        if statement["kind"] != "set" or address is None:
            continue
        selected, whole = snapshot.select(address)
        if not whole:
            raise ValueError("existing setter cuts an occurrence")
        for number in selected:
            for field, value in statement["fields"].items():
                curated[field].add(number)
                corrected[number][
                    {"spelling": "column", "type": "dtype"}.get(field, field)
                ] = value
                if field == "period":
                    spans = period_intervals(value)
                    if len(spans) != 1:
                        raise ValueError("noncontiguous corrected occurrence")
                    periods[number] = spans[0]

    workbook = list(records(args.frames / "scb-lisa.jsonl"))
    sections = json.loads((args.frames / "scb-lisa.sections.json").read_text())
    section_by_row = {r["at"]: s for s in sections for r in s["rows"]}
    source_rows = collections.defaultdict(list)
    for row in workbook:
        if row["kind"] == "occurrence":
            source_rows[row["locator"]["at"]].append(row)
    index = collections.defaultdict(list)
    for number, row in enumerate(corrected):
        index[row["column"].lower()].append(number)
    matched = {}
    report = {
        "rows": [],
        "original_unmatched": [],
        "lineage_unresolved": [],
        "identity_gaps": [],
    }
    counts = collections.Counter()
    omissions = {
        e["column"].lower()
        for e in tomllib.loads(
            (ROOT / "reg_meta_build/curation/registers/scb/lisa.toml").read_text()
        )["errata"]["column"]
    }
    for at, rows in sorted(source_rows.items()):
        first = rows[0]
        section = section_by_row[at]
        family = FAMILIES[
            section["text"]
            if first["table"] == "Individ årsoberoende"
            else first["table"]
        ]
        spelling = first["column"].lower()
        same_name = index[spelling]
        candidates = [
            n
            for n in same_name
            if converter.tables[*OWNER, corrected[n]["table"]] in family
        ]
        spans = [(r.get("from") or OPEN[0], r.get("to") or OPEN[1]) for r in rows]
        selected = [
            n
            for n in candidates
            if (periods[n] is None and spans == [OPEN])
            or (
                periods[n]
                and any(a <= periods[n][0] and periods[n][1] <= b for a, b in spans)
            )
        ]
        ambiguous = []
        for n in selected:
            if any(
                corrected[n]["table"] == corrected[m]["table"]
                and max((periods[n] or OPEN)[0], (periods[m] or OPEN)[0])
                <= min((periods[n] or OPEN)[1], (periods[m] or OPEN)[1])
                and corrected[n]["source_key"] != corrected[m]["source_key"]
                for m in selected
                if m != n
            ):
                ambiguous.append(n)
        selected = [n for n in selected if n not in ambiguous]
        if ambiguous:
            reason = "ambiguous rival source keys"
        elif selected:
            reason = "matched"
        elif not same_name:
            reason = (
                "known export omission (old errata.column)"
                if spelling in omissions
                else "2024-only absent export spelling"
                if all(a.startswith("2024") for a, _ in spans)
                else "spelling/documentation gap; no equivalence inferred"
            )
        elif not candidates:
            reason = "worksheet family mismatch"
        elif not any(
            periods[n] and max(a, periods[n][0]) <= min(b, periods[n][1])
            for n in candidates
            for a, b in spans
        ):
            reason = "period mismatch"
        else:
            reason = "no whole occurrence within workbook period"
        counts[reason] += 1
        matched[at] = selected
        report["rows"].append(
            {
                "at": at,
                "column": first["column"],
                "reason": reason,
                "occurrences": len(selected),
                "source_keys": sorted({corrected[n]["source_key"] for n in selected}),
            }
        )
        if spelling not in export_spellings:
            report["original_unmatched"].append(
                {
                    "at": at,
                    "column": first["column"],
                    "attached_occurrences": len(selected),
                    "reason": (
                        "known export omission (old errata.column)"
                        if spelling in omissions
                        else "2024-only absent export spelling"
                        if all(a.startswith("2024") for a, _ in spans)
                        else "spelling/documentation gap; no equivalence inferred"
                    ),
                }
            )
        origin = f"{first['locator']['input']}:{at}"
        for n in selected:
            raw = snapshot.rows[n][0]
            subject = converter.selector(raw)
            fields = {}
            if n not in curated["description"]:
                fields["description"] = first["label"]
            else:
                counts["description_occurrences_preserved"] += 1
            sensitive = first.get("sensitive")
            if (
                n >= source_count
                and sensitive is not None
                and sensitive != corrected[n].get("sensitive")
            ):
                counts["asserted_sensitivity_differences_preserved"] += 1
            if (
                sensitive is not None
                and sensitive != corrected[n].get("sensitive")
                and n not in curated["sensitive"]
            ):
                fields["sensitive"] = sensitive
            if fields:
                converter.add(
                    origin,
                    *OWNER,
                    {
                        "kind": "set",
                        "subject": subject,
                        "fields": fields,
                        "evidence": "LISA workbook: Beskrivning / Känslig1; whole occurrence within worksheet family and documented years.",
                    },
                )
    # Documents and lineage share the matched final membership map. Source-key
    # reuse must not fan a document out to unrelated variables after identity splits.
    endpoints = collections.defaultdict(set)
    targets_by_row = {}
    for at, selected in matched.items():
        targets = {
            effective[id(snapshot.rows[n][0])]
            for n in selected
            if id(snapshot.rows[n][0]) in effective
        }
        targets_by_row[at] = targets & used
        missing = [n for n in selected if id(snapshot.rows[n][0]) not in effective]
        if missing:
            report["identity_gaps"].append({"at": at, "occurrences": len(missing)})
        for n in selected:
            target = effective.get(id(snapshot.rows[n][0]))
            if target in used:
                endpoints[source_rows[at][0]["source_key"]].add(f"var:{target}")

    # Exact register names, public ledger names and source-stated parenthesized
    # abbreviations are evidence; similar strings and compound source texts are not.
    register_names = collections.defaultdict(set)
    for register in registers:
        owner = register["provider"], register["register"]
        public = converter.ledgers.get(owner, {}).get("public", owner[1])
        name = register.get("name") or ""
        for alias in [name, public, *re.findall(r"\(([^()]*)\)", name)]:
            if alias:
                register_names[alias.lower()].add(f"{owner[0]}/{public}")
    for link in (r for r in workbook if r["kind"] == "link"):
        name = link["object"]["register_name"]
        objects = register_names[name.lower()]
        at = link["locator"]["at"]
        if len(objects) != 1:
            report["lineage_unresolved"].append(
                {
                    "at": at,
                    "name": name,
                    "reason": "no unique exact register name/public name/source abbreviation",
                }
            )
            continue
        for target in sorted(targets_by_row.get(at, set())):
            converter.add(
                f"{link['locator']['input']}:{at}",
                *OWNER,
                {
                    "kind": "link",
                    "subject": f"var:{target}",
                    "relation": "derived_from",
                    "object": next(iter(objects)),
                    "evidence": f"LISA Grundregister: {name}.",
                },
            )

    normalize_sets(converter)
    collapse(converter)
    generated = [
        r["statement"]
        for r in converter.statements[OWNER].values()
        if any(not o.startswith("existing:") for o in r["origins"])
    ]
    counts.update(
        f"{s['kind']}.{f}"
        for s in generated
        for f in s.get("fields", {"relation": None})
    )
    text = original + "\n" + MARKER + "\n"
    for record in sorted(
        converter.statements[OWNER].values(),
        key=lambda r: json.dumps(r["statement"], sort_keys=True),
    ):
        if not any(not o.startswith("existing:") for o in record["origins"]):
            continue
        statement = dict(record["statement"])
        statement["evidence"] = (
            "\n".join(sorted(set(record["origins"])))
            + "\n\n"
            + statement.get("evidence", "")
        )
        text += (
            "\n[[statement]]\n"
            + "\n".join(f"{k} = {literal(v)}" for k, v in statement.items())
            + "\n"
        )
    text += "".join(authored_sets)
    (args.out / "curation.toml").write_text(text)
    markdown_path = ROOT / "curation/readers/markdown.toml"
    markdown = base(markdown_path) + "\n" + MARKER + "\n[subjects]\n"
    document_keys = {
        subject["endpoint"]["key"]
        for doc in records(args.frames / "lisa-docs.jsonl")
        for subject in doc.get("subjects", [])
        if subject["endpoint"]["kind"] == "variable"
    }
    for key, keys in sorted(endpoints.items()):
        if key not in document_keys:
            continue
        markdown += f"{literal(key)} = {literal([{'kind': 'variable', 'provider': 'scb', 'register': 'r34', 'key': k} for k in sorted(keys)])}\n"
    (args.out / "markdown.toml").write_text(markdown)
    report["counts"] = dict(counts)
    report["matched_occurrences"] = sum(len(v) for v in matched.values())
    report["grouping"] = converter.grouping_audit
    report["grouping_deferred"] = converter.grouping_deferred
    report["document_keys"] = len(endpoints.keys() & document_keys)
    (args.out / "report.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    )
    if args.write_curation:
        path.write_text(text)
        markdown_path.write_text(markdown)
    print(json.dumps(report["counts"], sort_keys=True))


if __name__ == "__main__":
    main()
