def _provider_id_by_slug(conn: sqlite3.Connection) -> dict[str, int]:
    return {
        slug: pid
        for pid, slug in conn.execute("SELECT provider_id, slug FROM provider")
    }


def _insert_providers(
    conn: sqlite3.Connection, providers: tuple[InvProvider, ...]
) -> int:
    """Mint + INSERT steward providers. Idempotent: an already-present slug is
    skipped (verify the name matches, like ``seed_providers``)."""
    existing = dict(conn.execute("SELECT slug, name FROM provider"))
    inserted = 0
    for p in providers:
        if p.slug in existing:
            if existing[p.slug] != p.name:
                raise _cfg_error(
                    f"extend-db provider {p.slug!r} already present with name "
                    f"{existing[p.slug]!r}, inventory gives {p.name!r}.",
                    "Reconcile the provider name with the live DB.",
                )
            continue
        conn.execute(
            "INSERT INTO provider (provider_id, slug, name) VALUES (?, ?, ?)",
            (mint("provider", p.slug), p.slug, p.name),
        )
        inserted += 1
    return inserted


def _insert_core_graph(
    conn: sqlite3.Connection,
    registers: tuple[InvRegister, ...],
    *,
    source_label: str,
) -> dict[str, int]:
    """INSERT the steward-private core graph (registers/variants/variables/
    states + the per-state alias row). Ids are deterministically minted
    high-band; the column lists mirror ``_reinsert_core_graph_from_ir`` (the
    materializer's sole-writer INSERTs). Slugs insert NULL — the steward TOML /
    incremental auto-derive fills them afterwards.

    Each register's provider must resolve to a live ``provider_id`` (a steward
    provider just inserted, or a built-in). A register whose provider is
    unknown is a structural defect (the inventory should have declared it)."""
    counts = {"registers": 0, "variants": 0, "variables": 0, "states": 0}
    provider_ids = _provider_id_by_slug(conn)

    for reg in registers:
        provider_id = provider_ids.get(reg.provider)
        if provider_id is None:
            raise _cfg_error(
                f"extend-db register {reg.provider}/{reg.key} names provider "
                f"{reg.provider!r}, which is neither declared in `providers` nor "
                "live in the DB.",
                "Declare the provider in the inventory `providers` array.",
            )
        register_id = mint("register", reg.provider, reg.key)
        conn.execute(
            "INSERT INTO register (register_id, provider_id, name, purpose, slug) "
            "VALUES (?, ?, ?, ?, NULL)",
            (register_id, provider_id, reg.name, reg.purpose),
        )
        counts["registers"] += 1

        for variant in reg.variants:
            register_variant_id = mint("variant", reg.provider, reg.key, variant.key)
            conn.execute(
                "INSERT INTO register_variant "
                "(register_variant_id, register_id, name, description, slug) "
                "VALUES (?, ?, ?, ?, NULL)",
                (register_variant_id, register_id, variant.name, variant.description),
            )
            counts["variants"] += 1

            for var in variant.variables:
                variable_id = mint(
                    "variable", reg.provider, reg.key, variant.key, var.key
                )
                conn.execute(
                    "INSERT INTO variable "
                    "(variable_id, register_id, provider_key, slug, name, "
                    " definition, description, source_register_text, "
                    " measurement_unit, source_register_id, source_label, "
                    " is_sensitive, is_identifier) "
                    "VALUES (?, ?, ?, NULL, ?, ?, ?, NULL, NULL, NULL, ?, ?, ?)",
                    (
                        variable_id,
                        register_id,
                        var.key,  # provider_key: the steward's variable key
                        var.name,
                        var.definition,
                        var.description,
                        source_label,
                        int(var.is_sensitive),
                        int(var.is_identifier),
                    ),
                )
                counts["variables"] += 1

                state_id = mint("state", reg.provider, reg.key, variant.key, var.key)
                valid_from, valid_to = _expand_window(var.valid_from, var.valid_to)
                conn.execute(
                    "INSERT INTO variable_state "
                    "(state_id, variable_id, register_variant_id, valid_from, "
                    " valid_to, data_type, data_length, delivery_column_name, "
                    " value_set_id, value_set_version_label, classification_id) "
                    "VALUES (?, ?, ?, ?, ?, ?, NULL, ?, NULL, '', NULL)",
                    (
                        state_id,
                        variable_id,
                        register_variant_id,
                        valid_from,
                        valid_to,
                        var.data_type,
                        var.column,
                    ),
                )
                counts["states"] += 1
                # Preserve the `variable_alias ⊇ state delivery columns`
                # invariant: every state column is also an alias row.
                conn.execute(
                    "INSERT INTO variable_alias "
                    "(variable_id, register_variant_id, delivery_column_name) "
                    "VALUES (?, ?, ?)",
                    (variable_id, register_variant_id, var.column),
                )
    return counts


def _apply_grafts(
    conn: sqlite3.Connection,
    grafts: tuple[InvGraft, ...],
    *,
    source_label: str,
    warn: Callable[[str], None],
) -> dict[str, int]:
    """Mint variable+state+alias for each graft onto its EXISTING
    ``(register, variant)`` (resolved by slug FQID). Gap-fill: skip a column
    already delivered as a state column there (case/diacritic-folded via
    ``LOWER``, mirroring ``materialize_grafts``).

    Banding mirrors ``variable_grafts`` PER TARGET PROVIDER: an SCB-register
    graft gets sequential ids just above the live SCB max (stays ``< 2^62``);
    a steward/SOS-register graft is ``mint()``-ed into the high band. Reads the
    live max off the COPY, so SCB-band grafts never collide with shipped PR1d
    grafts already in the global DB."""
    counts = {"grafts_minted": 0, "grafts_skipped": 0, "unresolved": 0}
    if not grafts:
        return counts

    # SCB-band sequential counters (only consumed by SCB-register grafts). Read
    # off the COPY's live extrema so we sit just above PR1d's shipped grafts.
    next_scb_var = (
        conn.execute(
            "SELECT COALESCE(MAX(variable_id), 0) FROM variable WHERE variable_id < ?",
            (_MINT_BIT,),
        ).fetchone()[0]
        + 1
    )
    next_scb_state = (
        conn.execute(
            "SELECT COALESCE(MAX(state_id), 0) FROM variable_state WHERE state_id < ?",
            (_MINT_BIT,),
        ).fetchone()[0]
        + 1
    )

    for g in grafts:
        variant_row = conn.execute(
            "SELECT rv.register_variant_id, r.register_id, p.slug "
            "FROM register_variant rv "
            "JOIN register r ON r.register_id = rv.register_id "
            "JOIN provider p ON p.provider_id = r.provider_id "
            "WHERE p.slug = ? AND r.slug = ? AND rv.slug = ?",
            (g.provider, g.register, g.variant),
        ).fetchone()
        if variant_row is None:
            counts["unresolved"] += 1
            continue
        register_variant_id, register_id, provider_slug = variant_row
        # Gap-fill only: skip if the column already delivers a state here.
        exists = conn.execute(
            "SELECT 1 FROM variable_state vs JOIN variable v "
            "ON vs.variable_id = v.variable_id "
            "WHERE v.register_id = ? AND vs.register_variant_id = ? "
            "AND LOWER(vs.delivery_column_name) = LOWER(?) LIMIT 1",
            (register_id, register_variant_id, g.column),
        ).fetchone()
        if exists:
            counts["grafts_skipped"] += 1
            continue

        if provider_slug == "scb":
            variable_id = next_scb_var
            state_id = next_scb_state
            next_scb_var += 1
            next_scb_state += 1
            if variable_id >= _MINT_BIT:  # pragma: no cover — pathological corpus
                raise _cfg_error(
                    "extend-db SCB graft ids would overflow the SCB band (2^62).",
                    "Too many SCB variables to graft — investigate.",
                )
        else:
            # Steward/SOS register graft: mint into the high band, keyed on the
            # graft coordinate so re-runs are deterministic.
            variable_id = mint(
                "graft-variable", g.provider, g.register, g.variant, g.column
            )
            state_id = mint("graft-state", g.provider, g.register, g.variant, g.column)

        conn.execute(
            "INSERT INTO variable (variable_id, register_id, provider_key, name, "
            "description, source_label) VALUES (?, ?, ?, ?, ?, ?)",
            (
                variable_id,
                register_id,
                f"graft:{g.column}",
                g.name,
                g.description,
                source_label,
            ),
        )
        conn.execute(
            "INSERT INTO variable_state (state_id, variable_id, register_variant_id, "
            "valid_from, valid_to, data_type, delivery_column_name) "
            "VALUES (?, ?, ?, ?, ?, ?, ?)",
            (
                state_id,
                variable_id,
                register_variant_id,
                _OPEN_FROM,
                _OPEN_TO,
                g.data_type,
                g.column,
            ),
        )
        conn.execute(
            "INSERT INTO variable_alias (variable_id, register_variant_id, "
            "delivery_column_name) VALUES (?, ?, ?)",
            (variable_id, register_variant_id, g.column),
        )
        counts["grafts_minted"] += 1

    if counts["unresolved"]:
        warn(
            f"  WARN extend-db: {counts['unresolved']:,} graft(s) did not resolve "
            "(register/variant slug churn) — regenerate the steward inventory"
        )
    return counts


def _apply_aliases(
    conn: sqlite3.Connection,
    aliases: tuple[InvAlias, ...],
    *,
    warn: Callable[[str], None],
) -> dict[str, int]:
    """INSERT OR IGNORE a ``variable_alias`` row on every variant in which the
    target variable (resolved by 3-seg FQID) has a state — mirrors
    ``delivery_enrichment._apply_aliases``. Idempotent; a slug that doesn't
    resolve (or a variable with no state) is counted ``unresolved``."""
    counts = {"aliases": 0, "unresolved": 0}
    for al in aliases:
        variable_row = conn.execute(
            "SELECT v.variable_id FROM variable v "
            "JOIN register r ON v.register_id = r.register_id "
            "JOIN provider p ON r.provider_id = p.provider_id "
            "WHERE p.slug = ? AND r.slug = ? AND v.slug = ?",
            (al.provider, al.register, al.variable),
        ).fetchone()
        variant_rows = conn.execute(
            "SELECT DISTINCT vs.register_variant_id FROM variable_state vs "
            "JOIN variable v ON vs.variable_id = v.variable_id "
            "JOIN register r ON v.register_id = r.register_id "
            "JOIN provider p ON r.provider_id = p.provider_id "
            "WHERE p.slug = ? AND r.slug = ? AND v.slug = ?",
            (al.provider, al.register, al.variable),
        ).fetchall()
        if variable_row is None or not variant_rows:
            counts["unresolved"] += 1
            continue
        variable_id = variable_row[0]
        for (register_variant_id,) in variant_rows:
            cur = conn.execute(
                "INSERT OR IGNORE INTO variable_alias "
                "(variable_id, register_variant_id, delivery_column_name) "
                "VALUES (?, ?, ?)",
                (variable_id, register_variant_id, al.delivery_column),
            )
            if cur.rowcount:
                counts["aliases"] += 1
    if counts["unresolved"]:
        warn(
            f"  WARN extend-db: {counts['unresolved']:,} alias(es) did not resolve "
            "(slug churn / no state) — regenerate the steward inventory"
        )
    return counts


