@dataclass(frozen=True)
class InvProvider:
    slug: str
    name: str


@dataclass(frozen=True)
class InvVariable:
    key: str
    name: str
    column: str
    definition: str | None
    description: str | None
    data_type: str | None
    is_identifier: bool
    is_sensitive: bool
    valid_from: str | None
    valid_to: str | None


@dataclass(frozen=True)
class InvVariant:
    key: str
    name: str
    description: str | None
    variables: tuple[InvVariable, ...]


@dataclass(frozen=True)
class InvRegister:
    provider: str
    key: str
    name: str
    purpose: str | None
    description: str | None
    variants: tuple[InvVariant, ...]


@dataclass(frozen=True)
class Inventory:
    steward: str
    source_label: str
    providers: tuple[InvProvider, ...]
    registers: tuple[InvRegister, ...]


