def _cfg_error(message: str, remediation: str) -> RegMetaError:
    return RegMetaError(
        exit_code=EXIT_CONFIG,
        code="extend_inventory_invalid",
        error_class="configuration",
        message=message,
        remediation=remediation,
    )


def _require_str(obj: dict, field: str, context: str) -> str:
    value = obj.get(field)
    if not isinstance(value, str) or not value.strip():
        raise _cfg_error(
            f"extend-db inventory {context} needs `{field}` as a non-empty "
            f"string, got {value!r}.",
            f'Give `"{field}": "<value>"` in the inventory JSON.',
        )
    return value.strip()


def _opt_str(obj: dict, field: str, context: str) -> str | None:
    value = obj.get(field)
    if value is None:
        return None
    if not isinstance(value, str):
        raise _cfg_error(
            f"extend-db inventory {context} `{field}` must be a string or null, "
            f"got {value!r}.",
            f'Give `"{field}": "<value>"` or `null`.',
        )
    stripped = value.strip()
    return stripped or None


def _opt_bool(obj: dict, field: str, context: str) -> bool:
    value = obj.get(field, False)
    if not isinstance(value, bool):
        raise _cfg_error(
            f"extend-db inventory {context} `{field}` must be a bool, got {value!r}.",
            f'Give `"{field}": true` / `false` or omit it.',
        )
    return value


def _reject_unknown_keys(obj: dict, allowed: frozenset[str], context: str) -> None:
    unknown = sorted(set(obj) - allowed)
    if unknown:
        raise _cfg_error(
            f"extend-db inventory {context} has unknown key(s): {unknown}.",
            f"Remove them; allowed keys are {sorted(allowed)}.",
        )


_INV_TOPLEVEL = frozenset({"steward", "source_label", "providers", "registers"})
_PROVIDER_KEYS = frozenset({"slug", "name"})
_REGISTER_KEYS = frozenset(
    {"provider", "key", "name", "purpose", "description", "variants"}
)
_VARIANT_KEYS = frozenset({"key", "name", "description", "variables"})
_VARIABLE_KEYS = frozenset(
    {
        "key",
        "name",
        "definition",
        "description",
        "column",
        "data_type",
        "is_identifier",
        "is_sensitive",
        "valid_from",
        "valid_to",
    }
)


def _list_of_dicts(raw: Any, context: str) -> list[dict]:
    if raw is None:
        return []
    if not isinstance(raw, list) or not all(isinstance(e, dict) for e in raw):
        raise _cfg_error(
            f"extend-db inventory `{context}` must be a list of objects, got "
            f"{type(raw).__name__}.",
            f'Give `"{context}": [ ... ]` (or omit it).',
        )
    return raw


def load_inventory(path: Path) -> Inventory:
    """Parse + strictly validate the inventory JSON. Structural defects raise
    ``RegMetaError(EXIT_CONFIG)``. Steward-only content has no FQID-resolution
    step: an unknown provider on a register is a hard structural error at
    materialize time (``_insert_core_graph``), not a lenient ``unresolved``
    count."""
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise _cfg_error(
            f"Could not read extend-db inventory {path}: {exc}",
            "Ensure the file exists and is valid JSON.",
        ) from exc
    if not isinstance(raw, dict):
        raise _cfg_error(
            f"extend-db inventory {path} must be a JSON object.",
            "Wrap the inventory in a top-level object.",
        )
    _reject_unknown_keys(raw, _INV_TOPLEVEL, "(top level)")
    steward = _require_str(raw, "steward", "(top level)")
    source_label = _require_str(raw, "source_label", "(top level)")

    providers = tuple(
        _load_provider(p, i)
        for i, p in enumerate(_list_of_dicts(raw.get("providers"), "providers"))
    )
    registers = tuple(
        _load_register(r, i)
        for i, r in enumerate(_list_of_dicts(raw.get("registers"), "registers"))
    )

    _reject_duplicate_provider_slugs(providers)
    _reject_duplicate_register_keys(registers)

    return Inventory(
        steward=steward,
        source_label=source_label,
        providers=providers,
        registers=registers,
    )


def _load_provider(obj: dict, idx: int) -> InvProvider:
    ctx = f"providers[{idx}]"
    _reject_unknown_keys(obj, _PROVIDER_KEYS, ctx)
    return InvProvider(
        slug=_require_str(obj, "slug", ctx),
        name=_require_str(obj, "name", ctx),
    )


def _load_register(obj: dict, idx: int) -> InvRegister:
    ctx = f"registers[{idx}]"
    _reject_unknown_keys(obj, _REGISTER_KEYS, ctx)
    provider = _require_str(obj, "provider", ctx)
    key = _require_str(obj, "key", ctx)
    variants_raw = _list_of_dicts(obj.get("variants"), f"{ctx}.variants")
    if not variants_raw:
        raise _cfg_error(
            f"extend-db inventory {ctx} ({provider}/{key}) needs at least one variant.",
            'Give `"variants": [ { "key": "_default", ... } ]`.',
        )
    return InvRegister(
        provider=provider,
        key=key,
        name=_require_str(obj, "name", ctx),
        purpose=_opt_str(obj, "purpose", ctx),
        description=_opt_str(obj, "description", ctx),
        variants=tuple(
            _load_variant(v, provider, key, i) for i, v in enumerate(variants_raw)
        ),
    )


def _load_variant(obj: dict, provider: str, reg_key: str, idx: int) -> InvVariant:
    ctx = f"registers[{provider}/{reg_key}].variants[{idx}]"
    _reject_unknown_keys(obj, _VARIANT_KEYS, ctx)
    key = _require_str(obj, "key", ctx)
    variables_raw = _list_of_dicts(obj.get("variables"), f"{ctx}.variables")
    if not variables_raw:
        raise _cfg_error(
            f"extend-db inventory {ctx} needs at least one variable.",
            'Give `"variables": [ { "key": "...", ... } ]`.',
        )
    seen: set[str] = set()
    variables: list[InvVariable] = []
    for i, v in enumerate(variables_raw):
        var = _load_variable(v, ctx, i)
        if var.key in seen:
            raise _cfg_error(
                f"extend-db inventory {ctx} has duplicate variable key {var.key!r}.",
                "Each variable key must be unique within its variant.",
            )
        seen.add(var.key)
        variables.append(var)
    return InvVariant(
        key=key,
        name=_require_str(obj, "name", ctx),
        description=_opt_str(obj, "description", ctx),
        variables=tuple(variables),
    )


def _load_variable(obj: dict, variant_ctx: str, idx: int) -> InvVariable:
    ctx = f"{variant_ctx}.variables[{idx}]"
    _reject_unknown_keys(obj, _VARIABLE_KEYS, ctx)
    return InvVariable(
        key=_require_str(obj, "key", ctx),
        name=_require_str(obj, "name", ctx),
        column=_require_str(obj, "column", ctx),
        definition=_opt_str(obj, "definition", ctx),
        description=_opt_str(obj, "description", ctx),
        data_type=_opt_str(obj, "data_type", ctx),
        is_identifier=_opt_bool(obj, "is_identifier", ctx),
        is_sensitive=_opt_bool(obj, "is_sensitive", ctx),
        valid_from=_opt_str(obj, "valid_from", ctx),
        valid_to=_opt_str(obj, "valid_to", ctx),
    )


def _reject_duplicate_provider_slugs(providers: tuple[InvProvider, ...]) -> None:
    seen: set[str] = set()
    for p in providers:
        if p.slug in seen:
            raise _cfg_error(
                f"extend-db inventory declares provider slug {p.slug!r} twice.",
                "Each provider slug must appear once.",
            )
        seen.add(p.slug)


def _reject_duplicate_register_keys(registers: tuple[InvRegister, ...]) -> None:
    seen: set[tuple[str, str]] = set()
    for r in registers:
        key = (r.provider, r.key)
        if key in seen:
            raise _cfg_error(
                f"extend-db inventory declares register {r.provider}/{r.key} twice.",
                "Each (provider, register key) must appear once.",
            )
        seen.add(key)


