def extend_db(
    base_db: Path,
    inventory_path: Path,
    db_dir: Path,
    *,
    steward: str,
    slug_dir: Path | None = None,
    skip_slugs: bool = False,
    pre_rename_hook: Callable[[Path], None] | None = None,
) -> dict[str, Any]:
    """Build a steward-flavored DB by overlaying ``inventory_path`` onto the
    released global DB ``base_db``, writing the result to ``<db_dir>/reg_meta.db``.

    Mirrors ``build_db``'s file discipline: copy the base DB to a ``.tmp``,
    insert on the copy (``foreign_keys=OFF`` during inserts, FK-check + VACUUM
    before commit), run ``pre_rename_hook`` against the tmp, then atomically
    rotate + rename into place. The base DB is a READ-ONLY input, never mutated.

    ``steward`` selects the steward slug dir
    (``reg_meta_build/fqid_slugs/<steward>/`` from a repo checkout) unless
    ``slug_dir`` is given; ``skip_slugs`` skips slug population entirely.

    Returns a counts dict: ``{providers, registers, variants, variables,
    states, aliases, grafts_minted, grafts_skipped, unresolved}``.
    """
    from .db import _populate_fts, _progress, rotate_db_to_prev
    from .fqid_slugs import populate_slugs, populate_variable_slugs, repo_slug_dir

    base_db = base_db.expanduser().resolve()
    db_dir = db_dir.expanduser().resolve()
    inventory_path = inventory_path.expanduser().resolve()

    if not base_db.is_file():
        raise RegMetaError(
            exit_code=EXIT_CONFIG,
            code="extend_base_db_not_found",
            error_class="configuration",
            message=f"Base global DB not found: {base_db}",
            remediation="Pass --base-db pointing at a released reg_meta.db.",
        )

    inventory = load_inventory(inventory_path)
    if inventory.steward != steward:
        raise _cfg_error(
            f"extend-db inventory steward {inventory.steward!r} does not match the "
            f"requested steward {steward!r}.",
            "Pass --steward matching the inventory, or fix the inventory.",
        )

    # Resolve the steward slug dir up front (before any file work) so a missing
    # dir fails fast rather than after the copy.
    steward_slug_dir: Path | None = None
    if not skip_slugs:
        if slug_dir is not None:
            steward_slug_dir = slug_dir.expanduser().resolve()
        else:
            global_dir = repo_slug_dir()
            if global_dir is None:
                raise RegMetaError(
                    exit_code=EXIT_CONFIG,
                    code="extend_slug_dir_not_found",
                    error_class="configuration",
                    message=(
                        "No --slug-dir given and no repo checkout found for the "
                        f"steward slug dir (fqid_slugs/{steward}/)."
                    ),
                    remediation=(
                        "Pass --slug-dir, run from a repo checkout, or "
                        "use --skip-slugs."
                    ),
                )
            steward_slug_dir = global_dir / steward
        if not steward_slug_dir.is_dir():
            raise RegMetaError(
                exit_code=EXIT_CONFIG,
                code="extend_slug_dir_not_found",
                error_class="configuration",
                message=f"Steward slug dir not found: {steward_slug_dir}",
                remediation=(
                    f"Create fqid_slugs/{steward}/ (with an UNFROZEN sentinel) or "
                    "pass --skip-slugs."
                ),
            )

    db_dir.mkdir(parents=True, exist_ok=True)
    final_path = db_dir / DB_FILENAME
    tmp_path = final_path.with_suffix(".db.tmp")
    if tmp_path.exists():
        tmp_path.unlink()

    # The base DB is a read-only INPUT — copy2 (preserves mtime) so the source
    # is never opened for write. All inserts happen on the copy.
    shutil.copy2(base_db, tmp_path)

    conn = sqlite3.connect(tmp_path)
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA synchronous=NORMAL")
    conn.execute("PRAGMA temp_store=MEMORY")
    conn.execute("PRAGMA foreign_keys=OFF")  # re-validate after inserts
    write_failed = True
    counts: dict[str, int] = {
        "providers": 0,
        "registers": 0,
        "variants": 0,
        "variables": 0,
        "states": 0,
        "aliases": 0,
        "grafts_minted": 0,
        "grafts_skipped": 0,
        "unresolved": 0,
    }
    try:
        _progress(f"extend-db: overlaying steward {steward!r} onto {base_db.name}")
        counts["providers"] = _insert_providers(conn, inventory.providers)
        core = _insert_core_graph(
            conn, inventory.registers, source_label=inventory.source_label
        )
        counts.update(core)
        graft_counts = _apply_grafts(
            conn, inventory.grafts, source_label=inventory.source_label, warn=_progress
        )
        alias_counts = _apply_aliases(conn, inventory.aliases, warn=_progress)
        counts["grafts_minted"] = graft_counts["grafts_minted"]
        counts["grafts_skipped"] = graft_counts["grafts_skipped"]
        counts["aliases"] = alias_counts["aliases"]
        counts["unresolved"] = graft_counts["unresolved"] + alias_counts["unresolved"]

        if not skip_slugs:
            assert steward_slug_dir is not None  # resolved above when not skipping
            # Additive register/variant slug population: strict=False because the
            # steward dir intentionally does NOT cover scb/sos (their rows keep
            # their published global slugs untouched — UPDATE only matches steward
            # TOML entries).
            populate_slugs(conn, steward_slug_dir, strict=False)
            # Incremental variable slugs: derive ONLY the new (NULL-slug)
            # variables, uniquifying against the published global slugs.
            populate_variable_slugs(conn, steward_slug_dir, incremental=True)

        # FTS rebuild: the overlay only INSERTs register / variable rows, so
        # those two indexes need a content-synced rebuild — cheap (a few extra
        # rows over the base) and avoids partial-sync bugs. These are
        # EXTERNAL-CONTENT FTS5 tables (content='register' etc.), so the index is
        # cleared with the special `'delete-all'` command — a plain
        # `DELETE FROM <fts>` corrupts an external-content index ("database disk
        # image is malformed"). value_code_fts is DELIBERATELY skipped: the
        # overlay never inserts a `value_code` row (grafts/aliases/steward
        # variables carry no value sets), so the index copied from the base DB is
        # already in sync — rebuilding it would re-insert ~4M rows for nothing on
        # a real flavored DB (#365 PR2 review).
        for fts in ("register_fts", "variable_fts"):
            conn.execute(f"INSERT INTO {fts}({fts}) VALUES('delete-all')")
        _populate_fts(conn, include_value_code=False)

        violations = list(conn.execute("PRAGMA foreign_key_check"))
        if violations:
            sample = ", ".join(f"{v[0]}#{v[1]}" for v in violations[:5])
            raise RegMetaError(
                exit_code=EXIT_CONFIG,
                code="foreign_key_violation",
                error_class="configuration",
                message=(
                    f"PRAGMA foreign_key_check returned {len(violations)} "
                    f"violation(s) before commit. Sample: {sample}."
                ),
                remediation=(
                    "The overlay inserted a row whose FK target is missing — "
                    "inspect the inventory's register/variant references."
                ),
            )
        conn.execute("PRAGMA foreign_keys=ON")
        conn.commit()
        conn.execute("VACUUM")  # must run outside a transaction
        write_failed = False
    finally:
        conn.close()
        if write_failed:
            tmp_path.unlink(missing_ok=True)

    # Pre-rename hook (flavored validation) runs against the tmp so a failure
    # aborts before the rename. The base global DB is untouched regardless.
    if pre_rename_hook is not None:
        try:
            pre_rename_hook(tmp_path)
        except BaseException:
            tmp_path.unlink(missing_ok=True)
            _unlink_wal_sidecars(tmp_path)
            raise

    _unlink_wal_sidecars(tmp_path)
    rotate_db_to_prev(final_path)
    tmp_path.rename(final_path)
    _progress(f"Flavored database written to {final_path}")

    # The contract return is the int counts dict; `db_path` rides alongside for
    # the CLI envelope (separate dict so `counts` stays homogeneously int-typed).
    result: dict[str, Any] = {**counts, "db_path": str(final_path)}
    return result


def _unlink_wal_sidecars(db_path: Path) -> None:
    for sidecar in ("-wal", "-shm"):
        db_path.with_name(db_path.name + sidecar).unlink(missing_ok=True)
