"""Steward-flavored DB overlay — ``extend-db`` (#365 PR2).

Build a *steward-flavored* reg_meta DB by overlaying steward-private content
onto a **released global DB**. The global DB (built by ``build-db`` from
SCB/SOS) is a READ-ONLY input: ``extend_db`` copies it, INSERTS the steward's
overlay on the copy, and writes the result to a new directory. The released
global DB is never mutated.

Where PR1 (``delivery_enrichment.py``) and PR1d (``variable_grafts.py``) carry
facts about the *shared* SCB/SOS world into the GLOBAL build, this overlay is
the steward-PRIVATE world: registers and variables that exist only for one
steward's flavor (e.g. SWECOV's bank-delivery registers), plus
pseudonym-column aliases and SCB-graft columns that the steward documents but
the global build doesn't carry.

This is the ARCHITECTURE PR: the machinery + synthetic-fixture proof. It ships
ZERO real steward content — the real SWECOV inventory is generated by an
(untracked) generator that targets the JSON contract documented below.

Inventory JSON contract
------------------------
``extend_db`` reads a single JSON file (the inventory) the generator produces::

    {
      "steward": "swecov",
      "source_label": "swecov-inventory-2025-12-11",
      "providers": [
        {"slug": "swedbank", "name": "Swedbank AB"}
      ],
      "registers": [
        {
          "provider": "swedbank", "key": "transaktioner",
          "name": "Transaktioner", "purpose": null, "description": null,
          "variants": [
            {
              "key": "_default", "name": "Transaktioner", "description": null,
              "variables": [
                {
                  "key": "belopp", "name": "Belopp", "definition": null,
                  "description": "Transaktionsbelopp i SEK.",
                  "column": "BELOPP", "data_type": "float",
                  "is_identifier": false, "is_sensitive": false,
                  "valid_from": null, "valid_to": null
                }
              ]
            }
          ]
        }
      ],
      "grafts": [
        {"register": "scb/agi", "variant": "agi-default",
         "column": "LANDSKOD_X", "name": "...", "description": "...",
         "data_type": "varchar"}
      ],
      "aliases": [
        {"variable": "scb/rtb/personnr", "register": "scb/rtb",
         "variant": "rtb-default", "delivery_column": "P1105_LopNr_PersonNr"}
      ]
    }

Top-level keys: ``steward`` (required str), ``source_label`` (required str —
stamped on every inserted/grafted ``variable.source_label``), and the four
optional operation arrays ``providers`` / ``registers`` / ``grafts`` /
``aliases`` (each may be absent or empty). Any OTHER top-level key is a
structural defect.

Operation kinds
---------------
1. **providers** — a steward-private data provider (a bank, an insurer). Minted
   ``provider_id = mint("provider", slug)`` (high band); INSERT-skipped if the
   slug already exists (idempotent; a slug/name mismatch fails like
   ``seed_providers``).
2. **registers/variants/variables/states** (nested) — the steward-private core
   graph. Deterministically minted high-band ids; inserted via the same column
   lists ``_reinsert_core_graph_from_ir`` uses. Each variable gets one
   open-range ``variable_state`` carrying its delivery ``column``, and that
   column also gets a ``variable_alias`` row (the ``variable_alias ⊇ state
   columns`` invariant). The register's ``provider`` must be defined in
   ``providers[]`` or already live in the DB.
3. **grafts** — a real column of a canonical SCB/SOS register the steward
   delivers (mirrors ``variable_grafts.materialize_grafts``). Gap-fill: skipped
   if the column already exists as a state column in that ``(register,
   variant)``. Minted in the TARGET provider's band — SCB → sequential just
   above the live SCB max (``< 2^62``); steward/SOS → ``mint()``.
4. **aliases** — a delivery-column alias on an EXISTING variable resolved by
   3-segment FQID (mirrors ``delivery_enrichment._apply_aliases``). INSERT OR
   IGNORE on every variant in which the variable has a state. This is where
   ``P1105_LopNr_*`` pseudonym names land.

Discipline
----------
* **Strict load, lenient resolve.** A structural inventory defect (unknown
  top-level key, missing required field, malformed FQID) fails with
  ``EXIT_CONFIG``. A graft/alias whose target FQID doesn't resolve is counted
  ``unresolved``, not fatal (mirrors the global overlays).
* **No-clobber.** The overlay only INSERTs. It never UPDATEs or DELETEs a
  global row — global registers/variants/variables and their slugs are
  byte-identical after the overlay.
* **No ``SCHEMA_VERSION`` bump** — rows on existing tables only.
"""

