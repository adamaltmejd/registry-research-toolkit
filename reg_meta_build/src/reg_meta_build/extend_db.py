# Open-range sentinel for an inserted state whose inventory gives no validity
# window — mirrors `variable_grafts` and the DDL `valid_to` default.
_OPEN_FROM = "0001-01-01"
_OPEN_TO = "9999-12-31"


def _expand_window(valid_from: str | None, valid_to: str | None) -> tuple[str, str]:
    """Expand the inventory's ISO 8601 ``valid_from`` / ``valid_to`` (each one of
    ``YYYY`` | ``YYYY-MM`` | ``YYYY-MM-DD`` | a period token, or None) to the
    full ten-char ISO date bounds ``variable_state`` requires (the DDL CHECKs
    ``length(valid_from)=10``). Mirrors the materializer's coarse-form expansion
    via ``period_token_to_bounds`` so a steward state's bounds agree with a
    later period query. A None end falls back to the open sentinel. A
    malformed token is a structural inventory defect (EXIT_CONFIG)."""

    def _expand(token: str | None, *, end: str, default: str) -> str:
        if token is None:
            return default
        try:
            lo, hi = period_token_to_bounds(token)
        except FqidError as exc:
            raise _cfg_error(
                f"extend-db inventory validity token {token!r} is not a valid "
                f"ISO 8601 period: {exc}",
                "Use YYYY, YYYY-MM, YYYY-MM-DD, or a period token.",
            ) from exc
        return hi if end == "hi" else lo

    return (
        _expand(valid_from, end="lo", default=_OPEN_FROM),
        _expand(valid_to, end="hi", default=_OPEN_TO),
    )


