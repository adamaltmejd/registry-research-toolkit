"""Steward-flavored DB overlay — ``extend-db`` (#365 PR2).

Build a *steward-flavored* reg_meta DB by overlaying steward-ONLY content onto
a **released global DB**. The global DB (built by ``build-db`` from SCB/SOS) is
a READ-ONLY input: ``extend_db`` copies it, INSERTS the steward's own
registers/variables on the copy, and writes the result to a new directory. The
released global DB is never mutated.

The flavor carries ONLY content that exists for one steward and nowhere else:
new providers and the registers/variables they deliver (e.g. SWECOV's
bank-delivery registers). Enrichment of EXISTING GLOBAL entities — backfilling
a global variable's description, recording a pseudonym alias on a global
variable, or grafting a shared SCB/SOS column — is GLOBAL-build work and lives
in the shipped PR1 mechanisms (``delivery_enrichment.py`` for descriptions and
aliases, ``variable_grafts.py`` for shared-column grafts), NOT here: a fact
about a global register belongs in the global build regardless of which steward
surfaced it.

This is the ARCHITECTURE PR: the machinery + synthetic-fixture proof. It ships
ZERO real steward content — the real SWECOV inventory is generated by an
(untracked) generator that targets the JSON contract documented below.

Inventory JSON contract
------------------------
``extend_db`` reads a single JSON file (the inventory) the generator produces::

    {
      "steward": "swecov",
      "source_label": "swecov-inventory-2025-12-11",
      "providers": [
        {"slug": "swedbank", "name": "Swedbank AB"}
      ],
      "registers": [
        {
          "provider": "swedbank", "key": "transaktioner",
          "name": "Transaktioner", "purpose": null, "description": null,
          "variants": [
            {
              "key": "_default", "name": "Transaktioner", "description": null,
              "variables": [
                {
                  "key": "belopp", "name": "Belopp", "definition": null,
                  "description": "Transaktionsbelopp i SEK.",
                  "column": "BELOPP", "data_type": "float",
                  "is_identifier": false, "is_sensitive": false,
                  "valid_from": null, "valid_to": null
                }
              ]
            }
          ]
        }
      ]
    }

Top-level keys: ``steward`` (required str), ``source_label`` (required str —
stamped on every inserted ``variable.source_label``), and the two optional
operation arrays ``providers`` / ``registers`` (each may be absent or empty).
Any OTHER top-level key is a structural defect.

Operation kinds
---------------
1. **providers** — a steward-private data provider (a bank, an insurer). Minted
   ``provider_id = mint("provider", slug)`` (high band); INSERT-skipped if the
   slug already exists (idempotent; a slug/name mismatch fails like
   ``seed_providers``).
2. **registers/variants/variables/states** (nested) — the steward-private core
   graph. Deterministically minted high-band ids; inserted via the same column
   lists ``_reinsert_core_graph_from_ir`` uses. Each variable gets one
   open-range ``variable_state`` carrying its delivery ``column``, and that
   column also gets a ``variable_alias`` row (the ``variable_alias ⊇ state
   columns`` invariant — an intrinsic part of defining the steward variable,
   NOT an alias onto a global variable). The register's ``provider`` must be
   defined in ``providers[]`` or already live in the DB.

Discipline
----------
* **Strict load.** A structural inventory defect (unknown top-level key, missing
  required field) fails with ``EXIT_CONFIG``. Steward-only content has no
  FQID-resolution step — an unknown provider on a register is a hard structural
  error, not a lenient ``unresolved`` count.
* **No-clobber.** The overlay only INSERTs steward-only rows. It never UPDATEs
  or DELETEs a global row — global registers/variants/variables and their slugs
  are byte-identical after the overlay.
* **No ``SCHEMA_VERSION`` bump** — rows on existing tables only.
"""

